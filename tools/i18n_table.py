LOCALES = ('zh_CN', 'zh_TW', 'en', 'ja', 'ko')


def message(key, loc):
    if loc in ('ja', 'ko'):
        return (JA if loc == 'ja' else KO)[key]
    return T[key][LOCALES.index(loc)]


def check():
    for name, d in (('ja', JA), ('ko', KO)):
        missing, extra = set(T) - set(d), set(d) - set(T)
        assert not missing and not extra, f'{name}: missing {sorted(missing)} extra {sorted(extra)}'
    for k in T:
        ph = sorted(re.findall(r'\{\d\}', T[k][0]))
        for loc in LOCALES:
            assert sorted(re.findall(r'\{\d\}', message(k, loc))) == ph, f'{k} placeholders differ in {loc}'


def main():
    check()
    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.join(here, '..', 'extension', '_locales')
    for loc in LOCALES:
        out = {k: {'message': message(k, loc)} for k in T}
        d = os.path.join(root, loc)
        os.makedirs(d, exist_ok=True)
